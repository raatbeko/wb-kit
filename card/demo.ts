function competitor(i: number, title: string, photos: number, video: boolean, chars: [string, string][]): CardText {
  const sentences = Array.from({ length: 10 + (i % 4) * 3 }, (_, k) => PHRASES[(i + k) % PHRASES.length]!);
  return {
    nmId: 180_000_000 + i * 1_234_567,
    subject: "Кружки",
    title,
    description: sentences.join(" "),
    characteristics: chars.map(([name, value]) => ({ name, value })),
    photos,
    hasVideo: video,
  };
}

