export function demoCardInput(now = new Date()): CardInput {
  const day = (t: number) => new Date(t).toISOString().slice(0, 10);
  const searchTexts: SearchText[] = QUERIES.map(([text, frequency, avgPosition, openCard, orders]) => ({
    text,
    frequency,
    weekFrequency: Math.round(frequency / 4.3),
    avgPosition,
    openCard,
    orders,
  }));
  return {
    generatedAt: now.toISOString(),
    demo: true,
    period: { from: day(now.getTime() - 30 * 86_400_000), to: day(now.getTime() - 86_400_000) },
    own: OWN,
    searchTexts,
    competitors: COMPETITORS,
    competitorsFrom: "выдача «кружка керамическая» (демо)",
  };
}
